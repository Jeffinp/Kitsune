#!/usr/bin/env bash
# vendor-codecs.sh LIBVPX_SRC OPUS_SRC: copy into user-apps/mediadec/vendor the part of libvpx (VP9
# decoder) and libopus (fixed-point decoder) that `mediadec` builds, unmodified, with the header
# files they include (found with `clang -MM`) and the licence files.
#
# LIBVPX_SRC: libvpx v1.15.2 (https://chromium.googlesource.com/webm/libvpx, tag v1.15.2; tarball
#   sha256 a981f53210bb99dee8967e10f330d0e73ba323e5cfbe83a08b1f1993db22427e).
# OPUS_SRC: opus 1.5.2 (https://downloads.xiph.org/releases/opus/opus-1.5.2.tar.gz, sha256
#   65c1d2f78b9f2fb20082c38cbe47c951ad5839345876e46941612ee87f9a7ce1).
#
# libvpx's configure-generated headers (vpx_config.h, *_rtcd.h, vpx_version.h) are not copied: the
# project keeps its own in user-apps/mediadec/csrc/vpx (generated by `configure --target=generic-gnu
# --disable-vp8 --disable-vp9-encoder --disable-multithread --disable-runtime-cpu-detect` and then
# trimmed by hand; see docs/design/midia.md). The lists below are what a decode-only program links
# (found by linking a probe against the full libraries with a link map).
set -eu
vpx=$1
opus=$2
here=$(cd "$(dirname "$0")/../.." && pwd)
dst=$here/user-apps/mediadec/vendor

VPX_C="vp9/common/vp9_alloccommon.c vp9/common/vp9_blockd.c vp9/common/vp9_common_data.c
vp9/common/vp9_entropy.c vp9/common/vp9_entropymode.c vp9/common/vp9_entropymv.c vp9/common/vp9_filter.c
vp9/common/vp9_frame_buffers.c vp9/common/vp9_idct.c vp9/common/vp9_loopfilter.c
vp9/common/vp9_pred_common.c vp9/common/vp9_quant_common.c vp9/common/vp9_reconinter.c
vp9/common/vp9_reconintra.c vp9/common/vp9_rtcd.c vp9/common/vp9_scale.c vp9/common/vp9_scan.c
vp9/common/vp9_seg_common.c vp9/common/vp9_thread_common.c vp9/common/vp9_tile_common.c
vp9/decoder/vp9_decodeframe.c vp9/decoder/vp9_decodemv.c vp9/decoder/vp9_decoder.c
vp9/decoder/vp9_detokenize.c vp9/decoder/vp9_dsubexp.c vp9/decoder/vp9_job_queue.c
vp9/vp9_dx_iface.c vp9/vp9_iface_common.c vpx/src/vpx_codec.c vpx/src/vpx_decoder.c
vpx_dsp/bitreader.c vpx_dsp/bitreader_buffer.c vpx_dsp/intrapred.c vpx_dsp/inv_txfm.c
vpx_dsp/loopfilter.c vpx_dsp/prob.c vpx_dsp/vpx_convolve.c vpx_dsp/vpx_dsp_rtcd.c vpx_mem/vpx_mem.c
vpx_scale/vpx_scale_rtcd.c vpx_scale/generic/yv12config.c vpx_scale/generic/yv12extend.c
vpx_util/vpx_thread.c
vpx_dsp/x86/inv_txfm_sse2.c vpx_dsp/x86/loopfilter_sse2.c"

OPUS_C="celt/bands.c celt/celt.c celt/celt_decoder.c celt/celt_lpc.c celt/cwrs.c celt/entcode.c
celt/entdec.c celt/entenc.c celt/kiss_fft.c celt/laplace.c celt/mathops.c celt/mdct.c celt/modes.c
celt/pitch.c celt/quant_bands.c celt/rate.c celt/vq.c
silk/CNG.c silk/LPC_analysis_filter.c silk/LPC_fit.c silk/LPC_inv_pred_gain.c silk/NLSF2A.c
silk/NLSF_decode.c silk/NLSF_stabilize.c silk/NLSF_unpack.c silk/PLC.c silk/bwexpander.c
silk/bwexpander_32.c silk/code_signs.c silk/dec_API.c silk/decode_core.c silk/decode_frame.c
silk/decode_indices.c silk/decode_parameters.c silk/decode_pitch.c silk/decode_pulses.c
silk/decoder_set_fs.c silk/gain_quant.c silk/init_decoder.c silk/lin2log.c silk/log2lin.c
silk/pitch_est_tables.c silk/resampler.c silk/resampler_private_AR2.c silk/resampler_private_IIR_FIR.c
silk/resampler_private_down_FIR.c silk/resampler_private_up2_HQ.c silk/resampler_rom.c
silk/shell_coder.c silk/sort.c silk/stereo_MS_to_LR.c silk/stereo_decode_pred.c silk/sum_sqr_shift.c
silk/table_LSF_cos.c silk/tables_LTP.c silk/tables_NLSF_CB_NB_MB.c silk/tables_NLSF_CB_WB.c
silk/tables_gain.c silk/tables_other.c silk/tables_pitch_lag.c silk/tables_pulses_per_block.c
src/opus.c src/opus_decoder.c"

conf=$here/user-apps/mediadec/csrc
# copy SRC_ROOT DEST FILES CFLAGS...: the files and every header under SRC_ROOT they include.
copy() {
  local root=$1 out=$2 files=$3
  shift 3
  mkdir -p "$out"
  for f in $files; do
    (cd "$root" && clang -MM -msse2 "$@" "$f") | tr ' \\' '\n\n' | grep -E '\.(c|h)$' |
      while read -r dep; do
        case "$dep" in /*) continue ;; esac
        mkdir -p "$out/$(dirname "$dep")"
        cp "$root/$dep" "$out/$dep"
      done
  done
}
rm -rf "$dst/libvpx" "$dst/opus"
copy "$vpx" "$dst/libvpx" "$VPX_C" -I. -I"$conf/vpx"
cp "$vpx/LICENSE" "$vpx/PATENTS" "$vpx/AUTHORS" "$dst/libvpx/"
echo "libvpx v1.15.2 (https://chromium.googlesource.com/webm/libvpx, tag v1.15.2), VP9 decoder subset" > "$dst/libvpx/VERSION"
copy "$opus" "$dst/opus" "$OPUS_C" -DHAVE_CONFIG_H -I"$conf/opus" -Iinclude -Icelt -Isilk -Isilk/fixed
cp "$opus/COPYING" "$opus/AUTHORS" "$dst/opus/"
echo "opus 1.5.2 (https://downloads.xiph.org/releases/opus/opus-1.5.2.tar.gz), fixed-point decoder subset" > "$dst/opus/VERSION"
du -sh "$dst/libvpx" "$dst/opus"

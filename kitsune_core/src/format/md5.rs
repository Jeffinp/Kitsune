//! MD5 (RFC 1321), streaming. Not for security: it is here to compare decoded media with the
//! references `ffmpeg -f framemd5` prints (one digest per frame), the usual check that a decoder is
//! bit-exact.

/// A running MD5.
#[derive(Clone, Debug)]
pub struct Md5 {
    state: [u32; 4],
    block: [u8; 64],
    fill: usize,
    len: u64,
}

impl Default for Md5 {
    fn default() -> Self {
        Self::new()
    }
}

const S: [u32; 64] = [
    7, 12, 17, 22, 7, 12, 17, 22, 7, 12, 17, 22, 7, 12, 17, 22, 5, 9, 14, 20, 5, 9, 14, 20, 5, 9,
    14, 20, 5, 9, 14, 20, 4, 11, 16, 23, 4, 11, 16, 23, 4, 11, 16, 23, 4, 11, 16, 23, 6, 10, 15,
    21, 6, 10, 15, 21, 6, 10, 15, 21, 6, 10, 15, 21,
];

/// `floor(abs(sin(i + 1)) * 2^32)`.
